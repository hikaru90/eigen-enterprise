import type { CoreApiLock, JsonSchema } from './lock'

/**
 * Generates `contracts/sdk/core-api.ts` from the lock (plan/phase-upgrades.md
 * §5: "the SDK is generated from the lock"): per tool its input and output
 * TypeScript types, and a typed `call(tool, input)` over a CoreApiTransport.
 * Part of `npm run contract:lock`; `npm run contract:check` fails when the
 * committed SDK differs from what the lock generates.
 */

const isSchema = (value: unknown): value is JsonSchema =>
  typeof value === 'object' && value !== null && !Array.isArray(value)

const literal = (value: unknown) => JSON.stringify(value)

const union = (types: string[]) => {
  const distinct = [...new Set(types)]
  return distinct.length === 1
    ? distinct[0]
    : distinct.map((t) => (t.includes(' ') ? `(${t})` : t)).join(' | ')
}

function pad(depth: number): string {
  return '  '.repeat(depth)
}

/** The TypeScript type of a JSON Schema (the subset zod emits; anything wider is `unknown`, which is honest). */
export function schemaToType(schema: JsonSchema, depth = 0): string {
  if ('const' in schema) return literal(schema.const)
  if (Array.isArray(schema.enum)) return union(schema.enum.map(literal))
  const members = schema.anyOf ?? schema.oneOf
  if (Array.isArray(members))
    return union(members.filter(isSchema).map((m) => schemaToType(m, depth)))
  if (Array.isArray(schema.allOf)) {
    return schema.allOf
      .filter(isSchema)
      .map((m) => `(${schemaToType(m, depth)})`)
      .join(' & ')
  }
  const types =
    typeof schema.type === 'string'
      ? [schema.type]
      : Array.isArray(schema.type)
        ? schema.type
        : null
  if (types === null) return 'properties' in schema ? objectType(schema, depth) : 'unknown'
  return union(types.map((type) => typeFor(String(type), schema, depth)))
}

function typeFor(type: string, schema: JsonSchema, depth: number): string {
  switch (type) {
    case 'string':
      return 'string'
    case 'number':
    case 'integer':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array':
      return isSchema(schema.items) ? `Array<${schemaToType(schema.items, depth)}>` : 'unknown[]'
    case 'object':
      return objectType(schema, depth)
    default:
      return 'unknown'
  }
}

function objectType(schema: JsonSchema, depth: number): string {
  const properties = isSchema(schema.properties)
    ? (schema.properties as Record<string, JsonSchema>)
    : {}
  const required = new Set(Array.isArray(schema.required) ? (schema.required as string[]) : [])
  const keys = Object.keys(properties)
  const extra = schema.additionalProperties
  const index = isSchema(extra)
    ? schemaToType(extra, depth + 1)
    : extra === false
      ? null
      : 'unknown'
  if (keys.length === 0)
    return index === null ? 'Record<string, never>' : `Record<string, ${index}>`
  const lines = keys.map(
    (key) =>
      `${pad(depth + 1)}${literal(key)}${required.has(key) ? '' : '?'}: ${schemaToType(properties[key], depth + 1)}`,
  )
  // Listed fields only: an open object's unlisted fields are not part of the contract.
  return `{\n${lines.join('\n')}\n${pad(depth)}}`
}

export function generateSdk(lock: CoreApiLock): string {
  const entries = lock.tools.map((tool) => {
    const output = tool.output === null ? 'unknown' : schemaToType(tool.output, 2)
    return `  ${literal(tool.name)}: {\n    input: ${schemaToType(tool.input, 2)}\n    output: ${output}\n  }`
  })
  return `// GENERATED by \`npm run contract:lock\` from contracts/core-api.lock.json — do not edit.
// The typed client of core-api ${lock.coreApi}: one entry per registry tool.
import type { CoreApiTransport } from './transport'

export { CoreApiCallError, mcpHttpTransport, type CoreApiTransport } from './transport'

export const CORE_API_VERSION = ${literal(lock.coreApi)}

export type CoreApiTools = {
${entries.join('\n')}
}

export type CoreApiToolName = keyof CoreApiTools
export type CoreApiInput<T extends CoreApiToolName> = CoreApiTools[T]['input']
export type CoreApiOutput<T extends CoreApiToolName> = CoreApiTools[T]['output']

export const CORE_API_TOOL_NAMES: readonly CoreApiToolName[] = [
${lock.tools.map((tool) => `  ${literal(tool.name)},`).join('\n')}
]

export type CoreApiClient = {
  call<T extends CoreApiToolName>(tool: T, input: CoreApiInput<T>): Promise<CoreApiOutput<T>>
}

export function createCoreApiClient(transport: CoreApiTransport): CoreApiClient {
  return {
    async call(tool, input) {
      return (await transport.callTool(tool, input)) as never
    },
  }
}
`
}
