const BY_NAME = new Map(FUNCTIONS.map((f) => [f.name, f]))

/** The function called `name` (any case, `_xlfn.` prefix ignored), else null. */
export function functionSig(name: string): FunctionSig | null {
  const bare = name
    .toUpperCase()
    .replace(/^_XLFN\./, '')
    .replace(/^_XLWS\./, '')
  return BY_NAME.get(bare) ?? null
}

/** Functions whose name starts with `prefix` (any case), in alphabetical order, at most `limit`. */
export function functionsStartingWith(prefix: string, limit = 12): FunctionSig[] {
  const upper = prefix.toUpperCase()
  const out: FunctionSig[] = []
  for (const sig of FUNCTIONS) {
    if (out.length >= limit) break
    if (sig.name.startsWith(upper)) out.push(sig)
  }
  return out
}

/**
 * "VLOOKUP(lookup_value, table_array, col_index_num, [range_lookup])" — the hint text, arguments
 * in Excel's tooltip form ([optional], "..." after a repeating one).
 */
export function signatureText(sig: FunctionSig): string {
  const parts = sig.args.map((arg) => (arg.optional ? `[${arg.name}]` : arg.name))
  if (sig.args.some((arg) => arg.repeat)) parts.push('...')
  return `${sig.name}(${parts.join(', ')})`
}
