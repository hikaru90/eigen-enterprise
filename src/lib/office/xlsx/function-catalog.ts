/**
 * Excel's worksheet functions with their argument names as Excel's English formula syntax shows
 * them in the tooltip (snake_case, `[optional]`, `...` after a repeating argument). Used by the
 * formula bar's function autocomplete and argument hints (./formula-edit.ts). Clean room: the spec
 * is Microsoft's public function reference; macro-only functions are left out, legacy
 * compatibility functions Excel still lists (STDEV, VAR, RANK, ...) are in.
 */
export type FunctionArg = { name: string; optional?: true; repeat?: true }
export type FunctionSig = { name: string; args: FunctionArg[] }

/**
 * One catalog entry from its tooltip form: `'lookup_value, table_array, [range_lookup]'`.
 * `[x]` is optional, a trailing `...` marks a repeating argument (both of a repeating pair).
 */
function fn(name: string, args = ''): FunctionSig {
  return {
    name,
    args: args
      .split(', ')
      .filter((token) => token !== '')
      .map((token) => {
        const repeat = token.endsWith('...')
        const bare = repeat ? token.slice(0, -3) : token
        const optional = bare.startsWith('[') && bare.endsWith(']')
        const arg: FunctionArg = { name: optional ? bare.slice(1, -1) : bare }
        if (optional) arg.optional = true
        if (repeat) arg.repeat = true
        return arg
      }),
  }
}

